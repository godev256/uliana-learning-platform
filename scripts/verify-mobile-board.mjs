import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch();
try {
 const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173/board');
 const stored=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('uliana-whiteboard-v2')));
 const viewport=page.locator('.board-workspace'), paper=page.locator('.board-paper').first();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.equal(await page.locator('.board-options').isVisible(),false);
 assert.ok((await paper.evaluate(el=>getComputedStyle(el).cursor)).includes('quill.svg'),'Drawing uses a feather cursor');
 const initialWidth=(await paper.boundingBox()).width;
 const rail=await page.locator('.board-controls').boundingBox(),work=await viewport.boundingBox();
 assert.ok(rail.x+rail.width<=work.x+1,'Phone tools must sit to the left of the sheet');
 assert.ok((await page.getByRole('button',{name:'Ручка',exact:true}).boundingBox()).y>(await page.getByRole('button',{name:'Ладошка',exact:true}).boundingBox()).y,'Phone tools form a vertical rail');
 assert.ok((await viewport.boundingBox()).height>500,'Most of the phone screen should be available for the sheet');
 await page.screenshot({path:'playwright-report/mobile-board-initial.png'});
 await page.getByRole('button',{name:'Приблизить лист',exact:true}).click();
 await page.waitForFunction(width=>document.querySelector('.board-paper').getBoundingClientRect().width>width*1.2,initialWidth);
 await page.getByRole('button',{name:'Лист по ширине экрана',exact:true}).click();
 await page.waitForFunction(width=>Math.abs(document.querySelector('.board-paper').getBoundingClientRect().width-width)<1,initialWidth);
 const cdp=await page.context().newCDPSession(page);
 const box=await viewport.boundingBox(),cx=box.x+box.width/2,cy=box.y+160;
 const send=(type,points)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(([x,y,id])=>({x,y,id}))});
 // Starting with one finger must not leave an accidental dot when a second joins.
 await send('touchStart',[[cx-35,cy,1]]);
 await send('touchStart',[[cx-35,cy,1],[cx+35,cy,2]]);
 await send('touchMove',[[cx-85,cy-10,1],[cx+85,cy+10,2]]);
 await send('touchEnd',[]);
 await page.waitForFunction(()=>document.querySelector('.board-zoom-reset').textContent!=='100%');
 assert.equal((await stored()).items.length,0,'Pinch must cancel an unfinished drawing');
 await page.waitForFunction(width=>document.querySelector('.board-paper').getBoundingClientRect().width>width*2,initialWidth);
 await page.getByRole('button',{name:'Ладошка',exact:true}).click();
 const beforePan=await viewport.evaluate(el=>[el.scrollLeft,el.scrollTop]);
 const view=await viewport.boundingBox(),px=view.x+view.width*.7,py=view.y+180;
 await send('touchStart',[[px,py,1]]);await send('touchMove',[[px-60,py-80,1]]);await send('touchEnd',[]);
 const afterPan=await viewport.evaluate(el=>[el.scrollLeft,el.scrollTop]);
 assert.ok(afterPan[0]>beforePan[0]+30 && afterPan[1]>beforePan[1]+30,'Hand pans the enlarged sheet in both directions');
 await page.getByRole('button',{name:'Ручка',exact:true}).click();
 await send('touchStart',[[view.x+130,view.y+170,1]]);await send('touchMove',[[view.x+190,view.y+200,1]]);await send('touchEnd',[]);
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('uliana-whiteboard-v2')).items.length===1);
 const stroke=(await stored()).items[0];
 assert.ok(stroke.points.length>1);
 // Compare a rendered pen endpoint with the physical touch coordinate after zoom and pan.
 const end=await page.locator('[data-shape-type="pen"]').evaluate(el=>{const p=el.getPointAtLength(el.getTotalLength());return new DOMPoint(p.x,p.y).matrixTransform(el.getScreenCTM()).toJSON();});
 assert.ok(Math.abs(end.x-(view.x+190))<2 && Math.abs(end.y-(view.y+200))<2,'Zoomed drawing must track the finger');
 await page.getByRole('button',{name:'Лист по ширине экрана',exact:true}).click();
 await page.getByRole('button',{name:/Цвет и толщина/}).click();assert.equal(await page.locator('.board-options').isVisible(),true);
 await page.getByRole('button',{name:'Красный',exact:true}).click();
 await page.getByRole('button',{name:/Цвет и толщина/}).click();
 await page.getByRole('button',{name:/Отменить/}).click();await page.waitForFunction(()=>JSON.parse(localStorage.getItem('uliana-whiteboard-v2')).items.length===0);
 await page.getByRole('button',{name:/Повторить/}).click();await page.waitForFunction(()=>JSON.parse(localStorage.getItem('uliana-whiteboard-v2')).items.length===1);
 await page.getByRole('button',{name:'Приблизить лист',exact:true}).click();
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Скачать конспект PDF',exact:true}).click();await(await download).saveAs('.local/mobile-board.pdf');
 await page.setViewportSize({width:320,height:740});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.getByRole('button',{name:'Лист по ширине экрана',exact:true}).click();
 await page.locator('summary[aria-label="Фигуры"]').click();
 await page.getByRole('button',{name:'Тетраэдр — 3D-визуализация',exact:true}).click();
 assert.equal(await page.locator('[data-shape-type="viz-tetrahedron"]').count(),1);
 await page.getByRole('button',{name:'Ручка',exact:true}).click();
 await viewport.evaluate(el=>{el.scrollTop=0;el.scrollLeft=0;});
 const body=await page.locator('[data-viz-body]').boundingBox(),visible=await viewport.boundingBox();
 const x=Math.max(body.x+20,visible.x+20),y=Math.max(body.y+25,visible.y+25);
 const count=(await stored()).items.filter(item=>item.type==='pen').length;
 await send('touchStart',[[x,y,1]]);await send('touchMove',[[x+40,y+25,1]]);await send('touchEnd',[]);
 await page.waitForFunction(count=>JSON.parse(localStorage.getItem('uliana-whiteboard-v2')).items.filter(item=>item.type==='pen').length===count+1,count);
 assert.equal((await stored()).items.find(item=>item.type==='viz-tetrahedron').rotation.join(','),'0,0,0','Pen over a 3D window must write without rotating the figure');
 await page.screenshot({path:'playwright-report/mobile-board-320.png'});
 assert.deepEqual(errors,[]);
 console.log('Mobile board checks passed: compact controls, 320/390px layout, pinch zoom, no stray strokes, hand panning, precise zoomed drawing, settings, history, figures and PDF.');
} finally {await browser.close();}
